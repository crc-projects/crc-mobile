#!/usr/bin/env python3
"""Generate the student-facing API reference and dependency-free C# client."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "openapi.yaml"
REFERENCE = ROOT / "docs" / "API_REFERENCE.md"
CLIENT = ROOT / "generated" / "CrcDirectoryApiClient.cs"


def pascal(value: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[_-]", value))


def reference_name(schema: dict) -> str:
    return schema["$ref"].rsplit("/", 1)[-1]


def csharp_type(schema: dict) -> str:
    if "$ref" in schema:
        return reference_name(schema)
    kind = schema.get("type", "object")
    if isinstance(kind, list):
        kind = next(item for item in kind if item != "null")
    if kind == "array":
        return f"List<{csharp_type(schema['items'])}>"
    if kind == "object":
        return "Dictionary<string, object?>"
    return {
        "string": "string",
        "integer": "long" if schema.get("format") == "int64" else "int",
        "number": "double",
        "boolean": "bool",
    }[kind]


def nullable_type(schema: dict, required: bool) -> str:
    name = csharp_type(schema)
    return name if required else f"{name}?"


def success_schema(operation: dict) -> dict:
    for status, response in operation["responses"].items():
        if str(status).startswith("2"):
            return response["content"]["application/json"]["schema"]
    raise ValueError(f"No JSON success response for {operation['operationId']}")


def methods(spec: dict) -> list[tuple[str, str, dict]]:
    return [
        (verb, path, operation)
        for path, item in spec["paths"].items()
        for verb, operation in item.items()
        if verb in {"get", "post"}
    ]


def generate_client(spec: dict) -> str:
    lines = [
        "// <auto-generated> Generated by tools/generate_api.py from openapi.yaml. </auto-generated>",
        "#nullable enable",
        "using System;",
        "using System.Collections.Generic;",
        "using System.Net;",
        "using System.Net.Http;",
        "using System.Net.Http.Json;",
        "using System.Text.Json;",
        "using System.Text.Json.Serialization;",
        "using System.Threading;",
        "using System.Threading.Tasks;",
        "",
        "namespace Crc.Mobile.Api;",
        "",
        "public sealed class CrcDirectoryApiClient",
        "{",
        "    private readonly HttpClient _httpClient;",
        "    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web)",
        "    {",
        "        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull",
        "    };",
        "",
        "    public CrcDirectoryApiClient(HttpClient httpClient)",
        "    {",
        "        _httpClient = httpClient ?? throw new ArgumentNullException(nameof(httpClient));",
        "        if (_httpClient.BaseAddress is null)",
        "            throw new ArgumentException(\"Set HttpClient.BaseAddress to the API origin.\", nameof(httpClient));",
        "    }",
        "",
    ]

    for verb, path, operation in methods(spec):
        name = pascal(operation["operationId"]) + "Async"
        route = path.lstrip("/")
        result_type = csharp_type(success_schema(operation))
        params = operation.get("parameters", [])
        if len(params) > 1 or any(param["in"] != "query" for param in params):
            raise ValueError(f"Unsupported parameters in {operation['operationId']}")
        query_arg = "string q, " if params else ""
        body = operation.get("requestBody")
        body_arg = f"{reference_name(body['content']['application/json']['schema'])} submission, " if body else ""
        lines.extend([
            f"    public async Task<{result_type}> {name}({query_arg}{body_arg}CancellationToken cancellationToken = default)",
            "    {",
        ])
        if params:
            lines.extend([
                "        ArgumentNullException.ThrowIfNull(q);",
                f'        var path = "{route}?{params[0]["name"]}=" + Uri.EscapeDataString(q);',
            ])
        else:
            lines.append(f'        const string path = "{route}";')
        if body:
            lines.append("        ArgumentNullException.ThrowIfNull(submission);")
        lines.extend([
            f"        using var request = new HttpRequestMessage(HttpMethod.{verb.title()}, path);",
        ])
        if body:
            lines.append("        request.Content = JsonContent.Create(submission, options: JsonOptions);")
        lines.extend([
            "        using var response = await _httpClient.SendAsync(request, HttpCompletionOption.ResponseHeadersRead, cancellationToken).ConfigureAwait(false);",
            "        await ThrowIfErrorAsync(response, cancellationToken).ConfigureAwait(false);",
            f"        return await response.Content.ReadFromJsonAsync<{result_type}>(JsonOptions, cancellationToken).ConfigureAwait(false)",
            "            ?? throw new JsonException(\"The API returned an empty JSON body.\");",
            "    }",
            "",
        ])

    lines.extend([
        "    private static async Task ThrowIfErrorAsync(HttpResponseMessage response, CancellationToken cancellationToken)",
        "    {",
        "        if (response.IsSuccessStatusCode) return;",
        "        var body = await response.Content.ReadAsStringAsync(cancellationToken).ConfigureAwait(false);",
        "        throw new CrcApiException(response.StatusCode, body);",
        "    }",
        "}",
        "",
        "public sealed class CrcApiException : Exception",
        "{",
        "    public HttpStatusCode StatusCode { get; }",
        "    public string ResponseBody { get; }",
        "    public string? Detail { get; }",
        "",
        "    public CrcApiException(HttpStatusCode statusCode, string responseBody)",
        "        : base($\"CRC API returned {(int)statusCode} ({statusCode}).\")",
        "    {",
        "        StatusCode = statusCode;",
        "        ResponseBody = responseBody;",
        "        try",
        "        {",
        "            using var json = JsonDocument.Parse(responseBody);",
        "            if (json.RootElement.TryGetProperty(\"detail\", out var detail) && detail.ValueKind == JsonValueKind.String)",
        "                Detail = detail.GetString();",
        "        }",
        "        catch (JsonException) { }",
        "    }",
        "}",
        "",
    ])

    for name, schema in spec["components"]["schemas"].items():
        if schema.get("type") != "object":
            raise ValueError(f"Unsupported model {name}")
        lines.extend([f"public sealed class {name}", "{"])
        required = set(schema.get("required", []))
        for json_name, property_schema in schema.get("properties", {}).items():
            property_name = pascal(json_name)
            property_type = nullable_type(property_schema, json_name in required)
            initializer = ""
            if json_name in required:
                if property_type == "string":
                    initializer = " = string.Empty;"
                elif property_type.startswith("List<"):
                    initializer = " = new();"
            lines.extend([
                f'    [JsonPropertyName("{json_name}")]',
                f"    public {property_type} {property_name} {{ get; set; }}{initializer}",
                "",
            ])
        if lines[-1] == "":
            lines.pop()
        lines.extend(["}", ""])

    return "\n".join(lines).rstrip() + "\n"


def markdown_type(schema: dict) -> str:
    if "$ref" in schema:
        return reference_name(schema)
    kind = schema.get("type", "object")
    if isinstance(kind, list):
        return " or ".join(kind)
    if kind == "array":
        return f"array of {markdown_type(schema['items'])}"
    return kind


def generate_reference(spec: dict) -> str:
    lines = [
        "<!-- Generated by tools/generate_api.py from openapi.yaml. Edit the spec, then regenerate. -->",
        f"# {spec['info']['title']}",
        "",
        spec["info"]["description"].strip(),
        "",
        "## Servers",
        "",
    ]
    for server in spec["servers"]:
        lines.append(f"- `{server['url']}`: {server['description']}")
    lines.extend(["", "## Endpoints", ""])
    for verb, path, operation in methods(spec):
        lines.extend([
            f"### {verb.upper()} `{path}`",
            "",
            operation["summary"],
            "",
            operation.get("description", "").strip(),
            "",
        ])
        for param in operation.get("parameters", []):
            lines.append(f"- Query `{param['name']}` ({markdown_type(param['schema'])}, {'required' if param.get('required') else 'optional'}): {param.get('description', '')}")
        if "requestBody" in operation:
            body_schema = operation["requestBody"]["content"]["application/json"]["schema"]
            lines.append(f"- JSON body: `{reference_name(body_schema)}`")
        lines.append(f"- Success JSON: `{markdown_type(success_schema(operation))}`")
        for status, response in operation["responses"].items():
            lines.append(f"- `{status}`: {response['description']}")
        lines.append("")
    lines.extend(["## Schemas", ""])
    for name, schema in spec["components"]["schemas"].items():
        lines.extend([f"### {name}", ""])
        if schema.get("description"):
            lines.extend([schema["description"].strip(), ""])
        lines.extend(["| JSON field | Type | Required | Notes |", "| --- | --- | --- | --- |"])
        required = set(schema.get("required", []))
        for field, field_schema in schema.get("properties", {}).items():
            note = field_schema.get("description", "").replace("|", "\\|").replace("\n", " ")
            lines.append(f"| `{field}` | {markdown_type(field_schema)} | {'yes' if field in required else 'no'} | {note} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if generated files are stale")
    args = parser.parse_args()
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    if spec.get("openapi") != "3.1.0":
        raise ValueError("Expected OpenAPI 3.1.0")
    outputs = {REFERENCE: generate_reference(spec), CLIENT: generate_client(spec)}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale generated file: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
